'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const worker=fs.readFileSync(path.join(__dirname,'worker.js'),'utf8');
const cut=worker.indexOf(";\naddEventListener('fetch'");
assert.ok(cut>0,'Worker HTML payload');
const html=JSON.parse(worker.slice('const HTML='.length,cut));
const csp=worker.slice(worker.indexOf("'content-security-policy':"),worker.indexOf("'content-security-policy':")+460);
assert.match(csp,/default-src 'none'/,'strict default CSP');
assert.match(csp,/script-src 'self' 'unsafe-inline' https:\/\/static\.cloudflareinsights\.com https:\/\/www\.googletagmanager\.com/,'Google support scripts and existing beacon');
assert.match(csp,/connect-src 'self' https:\/\/www\.google-analytics\.com https:\/\/region1\.google-analytics\.com/,'first-party and authorized Google Analytics endpoints');
assert.match(csp,/img-src 'self' https:\/\/raw\.githubusercontent\.com/,'local assets and existing art');
assert.match(csp,/frame-ancestors 'none'/,'no framing');
assert.doesNotMatch(html,/googletagmanager\.com\/(?:gtag|gtm)/,'no duplicate manual Google tag loader');
assert.doesNotMatch(html,/cdn-cgi\/zaraz\/s\.js/,'Zaraz GA4 collector disabled');
assert.match(html,/Cloudflare Google Tag Gateway delivers the Google Analytics 4 tag for pageviews/,'GA4 disclosed');
assert.match(html,/Your journal entries, letters, fortunes, and reflections stay in this browser/,'private writing disclaimer');
assert.match(html,/graves_orchard_between_worlds_v1/,'browser save key unchanged');
assert.equal((html.match(/data-ga4-config-init/g)||[]).length,1,'one GA4 initializer');
assert.match(html,/gtag\('config','G-Z569M020PS'\)/,'real GA4 config call');
assert.match(html,/gtag\('js',new Date\(\)\)/,'Google tag initial timestamp');
console.log(JSON.stringify({ok:true,mode:'Cloudflare Google Tag Gateway with native GA4 initialization',configCallCount:1,duplicateLoaders:0,sameOriginScriptAllowed:true,sameOriginCollectionAllowed:true,savedDataCompatible:true}));

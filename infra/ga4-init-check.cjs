'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync(path.join(__dirname,'ga4-init-worker.js'),'utf8');
const INIT="window.dataLayer=window.dataLayer||[];window.gtag=window.gtag||function(){dataLayer.push(arguments)};gtag('js',new Date());gtag('config','G-Z569M020PS');";
const hash='sha256-'+crypto.createHash('sha256').update(INIT,'utf8').digest('base64');
assert.equal(hash,'sha256-hrgh4GcqPTs6lCXTie51xggzfwgbgUgMCzF/oCgAlyM=','Expected pinned hash');
assert.match(src,/data-ga4-config-init/);
assert.match(src,/response.status!==200/);
assert.match(src,/if\(request.method!=='GET'\)/);
assert.match(src,/!type.startsWith\('text\/html'\)/);
assert.match(src,/target.pathname='\/'\+url.pathname.slice\(PREVIEW_PREFIX.length\)/);
assert.match(src,/headers.delete\('content-length'\)/);
assert.equal((src.match(/gtag\('config','G-Z569M020PS'\)/g)||[]).length,1);
const routes=[];
const html='<html><head><title>Test</title></head><body>hello</body></html>';
const initializer='<script data-ga4-config-init="G-Z569M020PS">'+INIT+'</script>';
let originHtml=html;
const upstream=[];
const fetchMock=async request=>{upstream.push({url:request.url,method:request.method});if(request.url.includes('/app.js'))return new Response('console.log("ok")',{status:200,headers:{'content-type':'application/javascript'}});return new Response(originHtml,{status:200,headers:{'content-type':'text/html; charset=utf-8','content-length':'999','etag':'abc'}})};
const env={URL,Request,Response,Headers,fetch:fetchMock,addEventListener(name,fn){routes.push({name,fn})}};
vm.runInNewContext(src,env,{filename:'ga4-init-worker.js'});
assert.equal(routes.length,1);assert.equal(routes[0].name,'fetch');
const fetchHandler=async(request)=>{let p;routes[0].fn({request,respondWith(x){p=x}});return p};
(async()=>{
let res=await fetchHandler(new Request('https://ptelectronics.net/index.html'));
const changed=await res.text();
assert.equal(res.status,200);
assert.ok(changed.includes(initializer));
assert.equal(changed.split('data-ga4-config-init').length-1,1);
assert.equal(res.headers.get('content-length'),null);
assert.equal(res.headers.get('x-ga4-init'),'v1');
originHtml=changed;
res=await fetchHandler(new Request('https://ptelectronics.net/again'));
assert.equal((await res.text()).split('data-ga4-config-init').length-1,1,'idempotent on already configured page');
res=await fetchHandler(new Request('https://ptelectronics.net/app.js'));
assert.equal(res.headers.get('x-ga4-init'),null,'assets are not modified');
assert.match(await res.text(),/console.log/);
originHtml=html;
res=await fetchHandler(new Request('https://ptelectronics.net/__ga4-preview/'));
assert.ok((await res.text()).includes(initializer));
assert.equal(upstream[upstream.length-1].url,'https://ptelectronics.net/');
console.log(JSON.stringify({ok:true,sha256:hash,configCount:1,htmlOnly:true,idempotent:true,previewWorks:true,passesAssets:true,sendsNoPrivateData:true}));
})().catch(e=>{console.error(e);process.exitCode=1});
